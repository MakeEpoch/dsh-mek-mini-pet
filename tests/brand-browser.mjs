import assert from 'node:assert/strict';
import { createRequire } from 'node:module';
import { mkdir } from 'node:fs/promises';
const require = createRequire(import.meta.url);
const { chromium } = process.env.DSH_PLAYWRIGHT_MODULE ? await import(process.env.DSH_PLAYWRIGHT_MODULE) : require('playwright');
const base = process.env.DSH_DEMO_URL || 'http://127.0.0.1:4173';
const browser = await chromium.launch({ headless: true, ...(process.env.CHROME_PATH ? { executablePath: process.env.CHROME_PATH } : {}), args: ['--no-sandbox'] });
const errors = [];
async function fixture(reducedMotion = 'reduce') {
  const page = await browser.newPage({ viewport: { width: 1200, height: 800 }, reducedMotion });
  page.on('pageerror', error => errors.push(error.stack));
  await page.goto(`${base}/tests/brand-capture.html`);
  await page.locator('dsh-pet-v7 .pet').waitFor();
  return page;
}
try {
  await mkdir('artifacts', { recursive: true });
  const page = await fixture(); const pet = page.locator('dsh-pet-v7');
  const header = await page.locator('#brand-row').boundingBox();
  await page.evaluate(() => document.querySelector('dsh-pet-v7').hide());
  await pet.locator('.logo-mark').waitFor({ state: 'visible' });
  const figure = await pet.locator('.logo-mark').boundingBox(), card = await pet.locator('.bubble').boundingBox(), next = await page.locator('#new-session').boundingBox();
  assert.equal(Math.round(figure.height), 64);
  assert.ok(Math.abs(card.y - figure.y) <= 8 && card.x >= figure.x + 50, 'task card is beside the complete figure');
  const toggle = await page.locator('#sidebar-toggle').boundingBox();
  assert.ok(card.x + card.width <= toggle.x - 4, 'card leaves the sidebar toggle accessible');
  assert.ok(card.width >= 150, 'task card uses the real header width, not the inline identity width');
  assert.equal(await page.locator('#brand-row [data-dsh-mini-pet-slot] > dsh-pet-v7').count(), 1, 'pet is an actual child of the sidebar row');
  assert.equal(await pet.evaluate(el => getComputedStyle(el).position), 'relative');
  await page.locator('#sidebar').evaluate(el => el.style.width = '390px');
  const wider = await pet.locator('.bubble').boundingBox();
  assert.ok(wider.width > card.width + 90, 'task card grows directly with sidebar width without resize events');
  await page.locator('#sidebar').evaluate(el => el.style.width = '280px');
  await page.reload(); await page.locator('#brand-row [data-dsh-mini-pet-slot] > dsh-pet-v7').waitFor();
  assert.equal(await pet.count(), 1, 'reload restores one embedded instance from saved preferences');
  assert.ok(next.y >= figure.y + figure.height, 'header reserves room above the new-session button');
  assert.equal(await pet.locator('.logo-avatar').evaluate(el => getComputedStyle(el).overflow), 'visible');
  assert.equal(await pet.locator('.logo-avatar').evaluate(el => getComputedStyle(el).borderRadius), '0px');
  assert.equal(await pet.locator('.logo-avatar').evaluate(el => getComputedStyle(el).backgroundColor), 'rgba(0, 0, 0, 0)');
  const sprite = await pet.locator('.logo-avatar .sprite').boundingBox();
  assert.ok(Math.abs(sprite.width / sprite.height - 192 / 208) < .01, 'sprite retains original cell ratio');
  await page.screenshot({ path: 'artifacts/sidebar-tucked.png', clip: { x: 0, y: 0, width: 360, height: 640 } });
  await pet.locator('.bubble').click();
  assert.deepEqual(await page.evaluate(() => window.__opened), ['pet-layout']);
  await pet.locator('.bubble').hover();
  assert.equal(await pet.locator('.bubble-close').isVisible(), false, 'no close X while tucked, including hover/focus');
  await page.evaluate(() => document.querySelector('dsh-pet-v7').dismissBubble());
  assert.equal(await pet.locator('.bubble').isVisible(), false);
  assert.equal(await pet.locator('.logo-mark').isVisible(), true, 'closing a card preserves the figure');
  await page.evaluate(() => { const el = document.querySelector('dsh-pet-v7'); el.updateTask({ ...el.snapshot.task }); });
  assert.equal(await pet.locator('.bubble').isVisible(), false);
  await page.evaluate(() => { const el = document.querySelector('dsh-pet-v7'); el.updateTask({ ...el.snapshot.task, revision: 'next-message' }); });
  assert.equal(await pet.locator('.bubble').isVisible(), true);
  await pet.locator('.bubble-restore').click(); await pet.locator('.pet').waitFor();
  assert.equal(await page.locator('#brand').isVisible(), true);
  assert.equal(Math.round((await page.locator('#brand-row').boundingBox()).height), Math.round(header.height));
  assert.equal(await pet.locator('.bubble-close').isVisible(), true, 'expanded task bubble retains its close control');
  // Resize, muted bubbles, both characters and anchor loss keep the companion accessible.
  await page.evaluate(() => { const el = document.querySelector('dsh-pet-v7'); el.configure({ character: 'dousha', showBubble: false }); el.hide(); });
  assert.equal(await pet.locator('.logo-mark').isVisible(), true);
  assert.equal(await pet.locator('.bubble-shell').isVisible(), false);
  await page.locator('#sidebar').evaluate(el => el.style.width = '232px');
  await page.evaluate(() => document.querySelector('dsh-pet-v7').measureBrandSlot());
  const narrow = await pet.locator('.logo-mark').boundingBox(); assert.ok(narrow.x + narrow.width < 232);
  await page.locator('#sidebar').evaluate(el => el.style.width = '56px');
  await page.evaluate(() => document.querySelector('dsh-pet-v7').measureBrandSlot());
  await pet.locator('.dock').waitFor();
  assert.equal(await pet.locator('.bubble-shell').isVisible(), false, 'collapsed rail does not overlay chat with a card');
  await page.locator('#brand-mark').evaluate(el => el.style.display = 'none');
  await page.evaluate(() => document.querySelector('dsh-pet-v7').measureBrandSlot());
  await pet.locator('.dock').waitFor(); await pet.locator('.dock').click();
  await page.evaluate(() => window.__dispose?.());
  assert.equal(await page.locator('#brand-row').evaluate(el => el.style.height), '');
  const wide = await fixture();
  await wide.locator('#sidebar').evaluate(el => el.style.width = '390px');
  await wide.evaluate(() => {
    const brand = document.querySelector('#brand'), span = document.createElement('span');
    span.id = 'brand'; span.innerHTML = brand.innerHTML; brand.replaceWith(span);
    document.querySelector('dsh-pet-v7').configure({ character: 'dousha' });
    document.querySelector('dsh-pet-v7').measureBrandSlot();
    document.querySelector('dsh-pet-v7').hide();
  });
  await wide.locator('dsh-pet-v7 .logo-mark').waitFor();
  const wideCard = await wide.locator('dsh-pet-v7 .bubble').boundingBox(), wideNext = await wide.locator('#new-session').boundingBox();
  assert.ok(wideNext.y >= wideCard.y + wideCard.height + 4, 'span brand in desktop shell also reserves the whole row');
  assert.equal(await wide.locator('#brand-name').isVisible(), false);
  await wide.locator('dsh-pet-v7 .bubble').hover();
  assert.equal(await wide.locator('dsh-pet-v7 .bubble-close').isVisible(), false);
  await wide.screenshot({ path: 'artifacts/sidebar-tucked-dousha.png', clip: { x: 0, y: 0, width: 390, height: 160 } });
  await wide.evaluate(() => window.__dispose?.());
  assert.equal(await wide.locator('#brand-name').isVisible(), true);
  assert.equal(await wide.locator('#brand-row').evaluate(el => el.style.height), '');
  const failed = await fixture();
  await failed.evaluate(() => { const pet = document.querySelector('dsh-pet-v7'); pet.hide(); pet.reportError(new Error('injected embedded UI fault')); });
  assert.equal(await failed.locator('dsh-pet-v7').count(), 0);
  assert.equal(await failed.locator('[data-dsh-mini-pet-slot]').count(), 0);
  assert.equal(await failed.locator('#brand').isVisible(), true);
  assert.equal(await failed.locator('#brand-row').evaluate(el => el.style.height), '');
  await failed.locator('#new-session').click();
  const moving = await fixture('no-preference');
  await moving.evaluate(() => document.querySelector('dsh-pet-v7').hide());
  await moving.waitForFunction(() => !!document.querySelector('.flyer')?.getAnimations().length);
  await moving.locator('dsh-pet-v7 .logo-mark').waitFor();
  await moving.locator('dsh-pet-v7 .logo-mark').click();
  await moving.waitForFunction(() => getComputedStyle(document.querySelector('#brand')).display !== 'none');
  await moving.waitForFunction(() => document.querySelector('.overlay').style.display === 'none');
  await moving.evaluate(() => window.__dispose?.());
  assert.equal(await moving.locator('#brand-row').evaluate(el => el.style.height), '');
  assert.deepEqual(errors, []);
  console.log('Sidebar checks passed: full figure, adjacent task card, header spacing, embedded responsive row, no tucked close button, navigation/dismissal, restore, narrow sidebar, character switch, fallback, animation and teardown.');
} finally { if (errors.length) console.error(errors); await browser.close(); }
