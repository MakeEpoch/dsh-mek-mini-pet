import { createRequire } from 'node:module';
import { mkdir, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import './embed-assets.mjs';
const require = createRequire(import.meta.url);
const esbuild = process.env.DSH_ESBUILD_MODULE ? require(process.env.DSH_ESBUILD_MODULE) : require('esbuild');
const root = fileURLToPath(new URL('../', import.meta.url));
const result = await esbuild.build({
  absWorkingDir: root, entryPoints: ['dsh/client.js'], bundle: true, write: false,
  format: 'cjs', platform: 'browser', target: 'es2022', legalComments: 'none',
});
const bundle = `// Generated by npm run build. dsh Client ModuleLoader bundle.\nwindow.__ModuleLoader__.load({\n  id: '@dsh/mini-pet',\n  factory: (require) => {\n    try {\n    const module = { exports: {} };\n    const exports = module.exports;\n${result.outputFiles[0].text}\n    return module.exports;\n    } catch (error) {\n      try { console.error('[mini-pet] module initialization failed; companion disabled', error); } catch {}\n      return { inject: [], apply() {} };\n    }\n  }\n});\n`;
await mkdir(new URL('../lib/', import.meta.url), { recursive: true });
await writeFile(new URL('../lib/client.js', import.meta.url), bundle);
console.log(`Built dsh client: ${Buffer.byteLength(bundle)} bytes`);
